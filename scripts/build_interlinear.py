"""Convert the pinned research corpus losslessly into offline chapter assets.

Acquire inputs separately with acquire_interlinear_research.py. No network here.
"""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
INPUT = ROOT / '.research/interlinear'
OUTPUT = ROOT / 'library/interlinear'
SNAPSHOT = '5d48325c55371efa69bc99debc2131d8974b15ab6116e49b00a07a95973c91be'
CORPUS = '3a58643986cb4f11cb45ecf1227ed33de1f1760bb0becc8556d0d6e99cf6420f'
ALIASES = dict(SNG='SOL', EZK='EZE', JOL='JOE', NAM='NAH', MRK='MAR', JHN='JOH', PHP='PHI', JAS='JAM', **{'1JN':'1JO','2JN':'2JO','3JN':'3JO'})
LANGUAGES = ['hebrew', 'aramaic', 'greek']
FIELDS = ['pos', 'bsbPos', 'language', 'text', 'transliteration', 'parsing', 'parsingFull', 'strongs', 'gloss']

def sha(data):
    return hashlib.sha256(data).hexdigest()

def encoded(data):
    return (json.dumps(data, ensure_ascii=False, separators=(',', ':')) + '\n').encode()

def main():
    report = json.loads((INPUT / 'corpus-report.json').read_text())
    files = report['files']
    assert sha('\n'.join(f["key"] + ':' + f['sha256'] for f in files).encode()) == CORPUS, 'Unpinned corpus hash list'
    assert len(files) == 1189 and len({f['key'] for f in files}) == 1189
    kjv = json.loads((ROOT / 'library/kjv/manifest.json').read_text())
    coordinates = {}
    for book in kjv['books']:
        for chapter in json.loads((ROOT / 'library/kjv' / (book['code'] + '.json')).read_text())['chapters']:
            coordinates[(book['code'], chapter['chapter'])] = [v['verse'] for v in chapter['verses']]
    OUTPUT.mkdir(parents=True, exist_ok=True)
    entries = []
    verse_count = word_count = 0
    for file in files:
        raw = (INPUT / 'chapters' / (file['key'] + '.json')).read_bytes()
        assert len(raw) == file['bytes'] and sha(raw) == file['sha256'], file['key']
        data = json.loads(raw)
        assert data['dataset']['id'] == 'bsb-interlinear' and data['dataset']['sha256'] == SNAPSHOT
        source_book, number = file['key'].split('-')
        number = int(number)
        book = ALIASES.get(source_book, source_book)
        assert data['book']['id'] == source_book and data['chapter']['number'] == number
        verses = []
        words = 0
        for verse in data['chapter']['content']:
            source = verse['words']
            for rank in ['pos', 'bsbPos']:
                assert sorted(w[rank] for w in source) == list(range(1, len(source) + 1)), (file['key'], verse['verse'], rank)
            rows = [[w[field] if field != 'language' else LANGUAGES.index(w[field]) for field in FIELDS] for w in source]
            verses.append([verse['verse'], rows])
            words += len(rows)
        assert [v[0] for v in verses] == coordinates.pop((book, number)), 'KJV verse coordinate mismatch'
        assert words == file['words'] and len(verses) == file['verses']
        output = encoded(dict(format=1, source='bsb-interlinear', book=book, sourceBook=source_book, chapter=number, verses=verses))
        name = f'{book}-{number}.json'
        (OUTPUT / name).write_bytes(output)
        entries.append(dict(book=book, sourceBook=source_book, chapter=number, file=name, bytes=len(output), sha256=sha(output), rawSha256=file['sha256'], verses=[v[0] for v in verses], words=words))
        verse_count += len(verses)
        word_count += words
    assert not coordinates and (verse_count, word_count) == (31102, 443625)
    manifest = encoded(dict(id='bsb-interlinear', schemaVersion=1, title='Berean interlinear companion', snapshot=SNAPSHOT,
                            rawCorpusSha256=CORPUS, license='Public Domain', source='https://bible.helloao.org/api/d/bsb-interlinear/books.json',
                            sourcePage='https://berean.bible/', licenseUrl='https://berean.bible/terms.htm',
                            columns=FIELDS, languages=LANGUAGES, verseCount=verse_count, wordCount=word_count, chapters=entries))
    (OUTPUT / 'manifest.json').write_bytes(manifest)
    (ROOT / 'src/core/interlinear-pins.ts').write_text('// Generated by scripts/build_interlinear.py from pinned inputs.\n'
        + f'export const INTERLINEAR_MANIFEST_SHA256 = "{sha(manifest)}";\n'
        + f'export const INTERLINEAR_MANIFEST_BYTES = {len(manifest)};\n')
    (OUTPUT / 'SOURCE-LICENSE.md').write_text('''# Berean interlinear companion

Original Hebrew, Aramaic and Greek words with Berean English glosses, transliteration,
grammar and source/English word-order ranks. These are not alignments to KJV English.
Scripture displayed separately in KJV retains its own source and rights notice.

The Berean Standard Bible and interlinear tables were dedicated to the public domain
on April 30, 2023. Source: https://berean.bible/ ; terms: https://berean.bible/terms.htm
The Free Use Bible API adapted the table to JSON: https://bible.helloao.org/docs/reference/datasets/
and https://bible.helloao.org/api/d/bsb-interlinear/books.json .
SwordDock converts that JSON to compact chapter tuples. All nine word fields,
including nulls, original ranks, repeated identifiers and diacritics are retained.
No textual corrections, new translations or Strong's-based alignments are added.
The original snapshot and each acquired chapter SHA-256 are in manifest.json.
This corpus does not include the API's separate STEPBible lexicon dataset.
''')
    print(json.dumps(dict(chapters=len(entries), verses=verse_count, words=word_count, bytes=sum(e['bytes'] for e in entries), manifestSha256=sha(manifest))))

if __name__ == '__main__':
    main()
